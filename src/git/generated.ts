import { git } from "./exec.ts";
import { assertSafePath, assertSafeRef } from "./repo.ts";

/** Generators put their marker at the top; a license header can push it down a few lines. */
const HEADER_LINES = 20;

/** Loose so git narrows cheaply in POSIX regex; `hasGeneratedMarker` decides. */
const GIT_PATTERN = "generated|do not (edit|modify)";

const MARKER =
  /@generated|do not (edit|modify)|auto[- ]?generated|automatically generated|generated (file|code)\b|(file|code) (is|was) generated|^\W*(code )?generated by\b/i;

/** A line that states the file is generated, as codegen tools write it. A mention in prose is not one. */
export function hasGeneratedMarker(line: string): boolean {
  return MARKER.test(line);
}

/** Paths whose blob at `ref` carries a generated marker in its first lines. */
export async function generatedPaths(
  cwd: string,
  ref: string,
  paths: readonly string[],
): Promise<Set<string>> {
  assertSafeRef(ref);
  for (const path of paths) {
    assertSafePath(path);
  }
  const generated = new Set<string>();
  if (paths.length === 0) {
    return generated;
  }
  const stdout = await git(
    cwd,
    [
      "--literal-pathspecs",
      "grep",
      "-z",
      "-n",
      "-i",
      "-I",
      "-E",
      "-e",
      GIT_PATTERN,
      ref,
      "--",
      ...paths,
    ],
    { allowFail: true },
  );
  for (const record of stdout.split("\n")) {
    const [refPath, line, text] = record.split("\0");
    if (refPath === undefined || line === undefined || text === undefined) {
      continue;
    }
    if (Number(line) <= HEADER_LINES && hasGeneratedMarker(text)) {
      generated.add(refPath.slice(ref.length + 1));
    }
  }
  return generated;
}
