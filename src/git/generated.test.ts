import assert from "node:assert/strict";
import { rmSync } from "node:fs";
import { mkdir, mkdtemp, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, describe, it } from "vite-plus/test";
import { initEmptyRepo } from "../test/init-repo.ts";
import { readDiff } from "./diff.ts";
import { git } from "./exec.ts";
import { generatedPaths, hasGeneratedMarker } from "./generated.ts";

const roots: string[] = [];

afterAll(() => {
  for (const root of roots) {
    rmSync(root, { recursive: true, force: true });
  }
});

describe("hasGeneratedMarker", () => {
  it("matches the markers codegen tools write", () => {
    for (const line of [
      "// Code generated by protoc-gen-go. DO NOT EDIT.",
      "# This file is automatically @generated by Cargo.",
      " * This file was automatically generated by graphql-codegen.",
      "<!-- Generated by typedoc -->",
      "// GENERATED CODE - DO NOT MODIFY BY HAND",
      "// <auto-generated />",
      "/* eslint-disable */ // this file is generated",
      "// THIS FILE IS GENERATED. Changes will be lost.",
      "# Generated file, see scripts/build.py",
    ]) {
      assert.equal(hasGeneratedMarker(line), true, line);
    }
  });

  it("ignores prose that mentions generation", () => {
    for (const line of [
      "Parses the reports generated by cargo.",
      "The generated bundle lives in dist/.",
      '"$schema": "https://json-schema.org/draft/2020-12/schema",',
      "export function generatedAt(): Date {",
      "description: Groups a git diff so humans can comprehend AI-generated code changes.",
      "// Generated code is slower here; see the benchmark.",
    ]) {
      assert.equal(hasGeneratedMarker(line), false, line);
    }
  });
});

describe("generatedPaths", () => {
  it("reads the marker from the first lines of the head blob", async () => {
    const root = await mkdtemp(join(tmpdir(), "comprehende-gen-"));
    roots.push(root);
    await initEmptyRepo(root);
    await mkdir(join(root, "src/gen"), { recursive: true });
    await mkdir(join(root, "src/å dir"), { recursive: true });
    await writeFile(join(root, "src/parse.ts"), "export const a = 1;\n", "utf8");
    await git(root, ["add", "."]);
    await git(root, ["commit", "-m", "base"]);
    const base = (await git(root, ["rev-parse", "HEAD"])).trim();

    await writeFile(
      join(root, "src/gen/api.ts"),
      "/* eslint-disable */\n// This file was automatically generated. DO NOT EDIT.\nexport type Api = {};\n",
      "utf8",
    );
    await writeFile(
      join(root, "src/å dir/report [1].ts"),
      "// @generated by the report tool\nexport const report = 1;\n",
      "utf8",
    );
    await writeFile(
      join(root, "src/parse.ts"),
      "/**\n * Parses the reports generated by cargo.\n */\nexport const a = 2;\n",
      "utf8",
    );
    await writeFile(
      join(root, "src/late.ts"),
      `${"// license\n".repeat(30)}// Code generated by hand-rolled-gen. DO NOT EDIT.\nexport const late = 1;\n`,
      "utf8",
    );
    await git(root, ["add", "."]);
    await git(root, ["commit", "-m", "head"]);
    const head = (await git(root, ["rev-parse", "HEAD"])).trim();

    const paths = ["src/gen/api.ts", "src/å dir/report [1].ts", "src/parse.ts", "src/late.ts"];
    assert.deepEqual([...(await generatedPaths(root, head, paths))].sort(), [
      "src/gen/api.ts",
      "src/å dir/report [1].ts",
    ]);
    assert.deepEqual(await generatedPaths(root, head, ["src/parse.ts"]), new Set());

    const files = await readDiff(root, base, head);
    const flagged = files.filter((file) => file.generated === true).map((file) => file.path);
    assert.deepEqual(flagged.sort(), ["src/gen/api.ts", "src/å dir/report [1].ts"]);
  });
});
